import 'package:flutter/material.dart';

import '../main.dart';
import '../models/agriculteur_model.dart';
import '../services/agriculteur_service.dart';
import '../services/ai_service.dart';
import '../widgets/brand_header.dart';
import '../widgets/custom_button.dart';
import 'agriculteur_form_screen.dart';
import 'cultures_screen.dart';
import 'materiels_screen.dart';
import 'parcelles_screen.dart';
import 'recoltes_screen.dart';

class AgriculteurDetailScreen extends StatefulWidget {
  const AgriculteurDetailScreen({super.key, required this.agriculteurId});

  final String agriculteurId;

  @override
  State<AgriculteurDetailScreen> createState() =>
      _AgriculteurDetailScreenState();
}

class _AgriculteurDetailScreenState extends State<AgriculteurDetailScreen> {
  final _service = AgriculteurService();
  final _aiService = AiService();
  Agriculteur? _agriculteur;
  bool _loading = true;
  String? _synthese;
  String? _syntheseSource;
  bool _generatingSynthese = false;

  @override
  void initState() {
    super.initState();
    _load();
  }

  Future<void> _load() async {
    setState(() => _loading = true);
    final agriculteur = await _service.getById(widget.agriculteurId);
    if (!mounted) return;
    setState(() {
      _agriculteur = agriculteur;
      _loading = false;
    });
  }

  Future<void> _genererSynthese(Agriculteur agriculteur) async {
    setState(() => _generatingSynthese = true);
    try {
      final texte = await _aiService.genererSynthese(agriculteur);
      setState(() {
        _synthese = texte;
        _syntheseSource = 'Generated by Gemini';
      });
    } catch (e) {
      setState(() {
        _synthese = _service.genererSynthese(agriculteur);
        _syntheseSource = _aiService.isConfigured
            ? 'AI call failed — showing offline estimate'
            : 'No Gemini API key configured — showing offline estimate';
      });
    } finally {
      setState(() => _generatingSynthese = false);
    }
  }

  Future<void> _edit() async {
    final agriculteur = _agriculteur;
    if (agriculteur == null) return;
    await Navigator.push(
      context,
      MaterialPageRoute(
        builder: (_) => AgriculteurFormScreen(agriculteur: agriculteur),
      ),
    );
    await _load();
  }

  Future<void> _toggleArchive() async {
    await _service.basculerArchivage(widget.agriculteurId);
    await _load();
  }

  Future<void> _delete() async {
    final confirmed = await showDialog<bool>(
      context: context,
      builder: (context) => AlertDialog(
        title: const Text('Delete farmer profile?'),
        content: const Text('This cannot be undone.'),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(context, false),
            child: const Text('Cancel'),
          ),
          TextButton(
            onPressed: () => Navigator.pop(context, true),
            child: const Text('Delete'),
          ),
        ],
      ),
    );
    if (confirmed != true) return;
    await _service.supprimer(widget.agriculteurId);
    if (!mounted) return;
    Navigator.pop(context);
  }

  @override
  Widget build(BuildContext context) {
    if (_loading) {
      return const Scaffold(
        body: Center(child: CircularProgressIndicator(color: forestGreen)),
      );
    }
    final agriculteur = _agriculteur;
    if (agriculteur == null) {
      return const Scaffold(body: Center(child: Text('Farmer not found.')));
    }
    final exploitation = agriculteur.exploitation;

    return Scaffold(
      backgroundColor: pageBackground,
      appBar: AppBar(
        backgroundColor: pageBackground,
        elevation: 0,
        iconTheme: const IconThemeData(color: inkGreen),
        actions: [
          IconButton(
            tooltip: 'Edit',
            onPressed: _edit,
            icon: const Icon(Icons.edit_outlined, color: inkGreen),
          ),
          PopupMenuButton<String>(
            icon: const Icon(Icons.more_vert_rounded, color: inkGreen),
            onSelected: (value) {
              if (value == 'archive') _toggleArchive();
              if (value == 'delete') _delete();
            },
            itemBuilder: (context) => [
              PopupMenuItem(
                value: 'archive',
                child: Text(agriculteur.archived ? 'Unarchive' : 'Archive'),
              ),
              const PopupMenuItem(value: 'delete', child: Text('Delete')),
            ],
          ),
        ],
      ),
      body: SafeArea(
        child: ListView(
          padding: const EdgeInsets.fromLTRB(24, 0, 24, 28),
          children: [
            const BrandHeader(compact: true),
            const SizedBox(height: 28),
            const CircleAvatar(
              radius: 42,
              backgroundColor: Color(0xFFD5E8D0),
              child: Icon(Icons.person_rounded, color: forestGreen, size: 44),
            ),
            const SizedBox(height: 14),
            Center(
              child: Text(
                agriculteur.fullName,
                style: const TextStyle(
                  color: inkGreen,
                  fontSize: 20,
                  fontWeight: FontWeight.w800,
                ),
              ),
            ),
            if (agriculteur.archived)
              const Center(
                child: Padding(
                  padding: EdgeInsets.only(top: 4),
                  child: Text(
                    'Archived',
                    style: TextStyle(
                      color: mutedGreen,
                      fontWeight: FontWeight.w700,
                    ),
                  ),
                ),
              ),
            const SizedBox(height: 28),
            _Section(
              title: 'Contact',
              children: [
                _InfoTile(Icons.phone_outlined, 'Phone', agriculteur.phone),
                if (agriculteur.email.isNotEmpty)
                  _InfoTile(Icons.mail_outline_rounded, 'Email', agriculteur.email),
                if (agriculteur.address.isNotEmpty)
                  _InfoTile(
                    Icons.location_on_outlined,
                    'Address',
                    agriculteur.address,
                  ),
              ],
            ),
            const SizedBox(height: 20),
            _Section(
              title: 'Exploitation',
              children: exploitation == null
                  ? [
                      const Padding(
                        padding: EdgeInsets.symmetric(
                          horizontal: 18,
                          vertical: 14,
                        ),
                        child: Text('No exploitation linked yet.'),
                      ),
                    ]
                  : [
                      _InfoTile(
                        Icons.business_outlined,
                        'Name',
                        exploitation.name,
                      ),
                      _InfoTile(
                        Icons.map_outlined,
                        'Location',
                        exploitation.location,
                      ),
                      _InfoTile(
                        Icons.straighten_outlined,
                        'Size',
                        '${exploitation.sizeHectares} ha',
                      ),
                      _InfoTile(
                        Icons.grass_rounded,
                        'Main crop',
                        exploitation.mainCrop,
                      ),
                    ],
            ),
            const SizedBox(height: 20),
            Text(
              'Activities & resources',
              style: Theme.of(context).textTheme.titleLarge,
            ),
            const SizedBox(height: 12),
            Row(
              children: [
                Expanded(
                  child: _ShortcutCard(
                    icon: Icons.landscape_outlined,
                    label: 'Parcelles',
                    screen: const ParcellesScreen(),
                  ),
                ),
                const SizedBox(width: 12),
                Expanded(
                  child: _ShortcutCard(
                    icon: Icons.grass_rounded,
                    label: 'Cultures',
                    screen: const CulturesScreen(),
                  ),
                ),
              ],
            ),
            const SizedBox(height: 12),
            Row(
              children: [
                Expanded(
                  child: _ShortcutCard(
                    icon: Icons.agriculture_rounded,
                    label: 'Récoltes',
                    screen: const RecoltesScreen(),
                  ),
                ),
                const SizedBox(width: 12),
                Expanded(
                  child: _ShortcutCard(
                    icon: Icons.handyman_outlined,
                    label: 'Matériels',
                    screen: const MaterielsScreen(),
                  ),
                ),
              ],
            ),
            const SizedBox(height: 24),
            Card(
              elevation: 0,
              color: Colors.white,
              shape: RoundedRectangleBorder(
                borderRadius: BorderRadius.circular(18),
                side: const BorderSide(color: borderGreen),
              ),
              child: Padding(
                padding: const EdgeInsets.all(18),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Row(
                      children: [
                        const Icon(Icons.auto_awesome, color: forestGreen),
                        const SizedBox(width: 10),
                        Text(
                          'AI summary',
                          style: Theme.of(context).textTheme.titleLarge,
                        ),
                      ],
                    ),
                    const SizedBox(height: 10),
                    Text(
                      _synthese ??
                          'Generate a quick summary of what needs attention '
                              'on this exploitation.',
                    ),
                    if (_syntheseSource != null) ...[
                      const SizedBox(height: 6),
                      Text(
                        _syntheseSource!,
                        style: const TextStyle(
                          color: mutedGreen,
                          fontSize: 11.5,
                          fontWeight: FontWeight.w600,
                        ),
                      ),
                    ],
                    const SizedBox(height: 14),
                    CustomButton(
                      label: 'Generate summary',
                      outlined: true,
                      isLoading: _generatingSynthese,
                      onPressed: _generatingSynthese
                          ? null
                          : () => _genererSynthese(agriculteur),
                    ),
                  ],
                ),
              ),
            ),
          ],
        ),
      ),
    );
  }
}

class _Section extends StatelessWidget {
  const _Section({required this.title, required this.children});

  final String title;
  final List<Widget> children;

  @override
  Widget build(BuildContext context) {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Text(title, style: Theme.of(context).textTheme.titleLarge),
        const SizedBox(height: 12),
        Card(
          elevation: 0,
          color: Colors.white,
          shape: RoundedRectangleBorder(
            borderRadius: BorderRadius.circular(18),
            side: const BorderSide(color: borderGreen),
          ),
          child: Column(
            children: [
              for (var i = 0; i < children.length; i++) ...[
                if (i > 0) const Divider(height: 1, color: borderGreen),
                children[i],
              ],
            ],
          ),
        ),
      ],
    );
  }
}

class _InfoTile extends StatelessWidget {
  const _InfoTile(this.icon, this.label, this.value);

  final IconData icon;
  final String label;
  final String value;

  @override
  Widget build(BuildContext context) {
    return ListTile(
      leading: Icon(icon, color: forestGreen),
      title: Text(label),
      subtitle: Text(value),
    );
  }
}

class _ShortcutCard extends StatelessWidget {
  const _ShortcutCard({
    required this.icon,
    required this.label,
    required this.screen,
  });

  final IconData icon;
  final String label;
  final Widget screen;

  @override
  Widget build(BuildContext context) {
    return InkWell(
      borderRadius: BorderRadius.circular(18),
      onTap: () => Navigator.push(
        context,
        MaterialPageRoute(builder: (_) => screen),
      ),
      child: Container(
        padding: const EdgeInsets.symmetric(vertical: 16, horizontal: 14),
        decoration: BoxDecoration(
          color: Colors.white,
          borderRadius: BorderRadius.circular(18),
          border: Border.all(color: borderGreen),
        ),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Icon(icon, color: forestGreen),
            const SizedBox(height: 8),
            Text(
              label,
              style: const TextStyle(
                color: inkGreen,
                fontWeight: FontWeight.w800,
              ),
            ),
          ],
        ),
      ),
    );
  }
}
